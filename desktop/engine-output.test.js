const assert = require('assert/strict');
const { EventEmitter } = require('events');
const { NativeMixOutput } = require('./engine-output');

let time = 0;
const children = [];
function spawnProcess() {
  const child = new EventEmitter();
  child.stdin = new EventEmitter();
  child.stdin.writable = true;
  child.stdin.write = (data, callback) => { child.records.push(Buffer.from(data)); callback?.(); return true; };
  child.stdout = new EventEmitter(); child.stderr = new EventEmitter();
  child.exitCode = null; child.records = [];
  children.push(child); return child;
}
const output = new NativeMixOutput({ enabled: true, helperPath: process.execPath, spawnProcess, now: () => time, logger: {} });
const config = { sources: [{ hash: 42, gain: .5, muted: false, busMask: 1n }], buses: [{ gain: .75 }] };
assert(output.sendConfig(config));
const originalRecord = Buffer.from(children[0].records[1]);
assert.equal(children[0].records[0].toString('ascii', 0, 4), 'MSMP');
assert.equal(originalRecord.toString('ascii', 0, 4), 'MCFG');
children[0].stderr.emit('data', 'error: endpoint unavailable');
children[0].emit('exit', 2, null);
for (let i = 0; i < 100; i++) assert.equal(output.writePacket(42, i, new Float32Array(960)), false);
assert.equal(children.length, 1, 'a failed endpoint must not respawn on every PCM packet');
assert.equal(output.status().lastError, 'error: endpoint unavailable');
time = 1000;
assert(output.writePacket(42, 100, new Float32Array(960)));
assert.equal(children.length, 2);
assert.deepEqual(children[1].records[1], originalRecord, 'restored graph precedes resumed PCM');
assert.equal(children[1].records[2].toString('ascii', 0, 4), 'PCM ');
children[1].emit('exit', 2, null);
time = 2000;
assert.equal(output.writePacket(42, 101, new Float32Array(960)), false, 'repeated failures back off exponentially');
assert.equal(output.sendConfig({ ...config, sources: [{ ...config.sources[0], muted: true }] }), false);
time = 3000;
assert(output.writePacket(42, 102, new Float32Array(960)));
assert.equal(children[2].records[1].readUInt8(28), 1, 'latest mute survives a failed output and is replayed');
children[2].stdout.emit('data', '{"type":"engine.stats","targetMs":25,"renderedMs":1000,"sources":[]}\n');
assert.equal(output.status().lastError, null, 'successful render stats clear the failure');
children[2].emit('error', Error('process lost'));
time = 3500;
assert.equal(output.writePacket(42, 103, new Float32Array(960)), false);
time = 4000;
assert(output.writePacket(42, 104, new Float32Array(960)), 'healthy output resets backoff to one second');
assert.equal(children.length, 4);
children[2].emit('exit', 2, null);
assert.equal(output.child, children[3], 'late events from an old child cannot retire the recovered output');
console.log('engine-output recovery/backoff/config replay tests passed');
